function load(file) {
  file = path.resolve(file);
  if (cache.has(file)) return cache.get(file).exports;
  const m = new Module(file, module); m.filename = file; m.paths = module.paths; cache.set(file,m);
  const original = m.require.bind(m);
  m.require = id => {
    if (id === '@/lib/db' || id === './db') return { db: () => db };
    if (id === 'next/headers') return { cookies: () => ({ get: key => jar.has(key) ? { value: jar.get(key) } : undefined, set: (key,value) => jar.set(key,value) }) };
    if (id === 'next/cache') return { revalidatePath: () => {} };
    if (id === '@/lib/mail') return { sendMail: async (...args) => { if (mailFails) throw Error('offline'); sent.push(args); } };
    if (id.startsWith('@/')) return load('src/'+id.slice(2)+'.ts');
    if (id.startsWith('.')) return load(path.resolve(path.dirname(file),id)+'.ts');
    return original(id);
  };
  m._compile(ts.transpileModule(fs.readFileSync(file,'utf8'),{ compilerOptions:{ module:ts.ModuleKind.CommonJS,esModuleInterop:true,target:ts.ScriptTarget.ES2020 }}).outputText,file);
  return m.exports;
}
